import requests
from bs4 import BeautifulSoup
import random

def fetch_free_proxies():
    print("🔄 Đang quét và lấy danh sách Proxy miễn phí từ Internet...")
    proxies = []
    url = "https://free-proxy-list.net/"
    
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
    }
    
    try:
        response = requests.get(url, headers=headers, timeout=10)
        if response.status_code == 200:
            soup = BeautifulSoup(response.text, 'html.parser')
            
            # Tìm cái bảng chứa danh sách IP trên trang web
            table = soup.find('table', class_='table-striped')
            if table:
                rows = table.find_all('tr')
                for row in rows[1:]:  # Bỏ qua dòng tiêu đề đầu tiên
                    cols = row.find_all('td')
                    if len(cols) > 1:
                        ip = cols[0].text.strip()
                        port = cols[1].text.strip()
                        # Đóng gói thành định dạng http://ip:port
                        proxies.append(f"http://{ip}:{port}")
                        
        print(f"✅ Đã gom được {len(proxies)} Proxy Free về bộ nhớ!")
    except Exception as e:
        print(f"❌ Lỗi khi tự động lấy proxy free: {e}")
        
    return proxies

